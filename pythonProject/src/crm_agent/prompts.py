SENTIMENT_ANALYSIS_PROMPT = """你是一个保险CRM客户情感分析专家。请分析以下客户的交互记录，提取关键洞察。

## 客户交互记录
{interactions}

## 分析要求
1. **整体情感倾向** (overall_sentiment): 偏向正面 / 中性 / 偏向负面
2. **情感趋势** (sentiment_trend): 上升(越来越好) / 平稳 / 下滑(越来越差)
3. **决策信号** (decision_signals): 客户表现出的购买/续保/流失决策信号列表
4. **风险标记** (risk_flags): 需要注意的负面信号，如投诉、不满、竞品比较等

请以JSON格式输出（只输出JSON，不要其他内容）：
{{
    "overall_sentiment": "...",
    "sentiment_trend": "...",
    "decision_signals": ["信号1", "信号2"],
    "risk_flags": ["风险1", "风险2"]
}}"""


