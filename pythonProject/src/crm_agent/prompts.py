CHURN_PREDICTION_PROMPT = """你是一个保险CRM流失预测分析专家。基于客户数据，综合评估流失风险。

## 客户数据
{context}

## 分析要求
1. **流失风险评分** (churn_risk): 0-100的整数，数值越高越可能流失
2. **风险因素** (risk_factors): 导致流失风险的具体原因列表
3. **建议行动** (recommended_actions): 挽回客户的具体建议措施

### 评分参考基准
- 规则引擎给出的基础风险分已包含在数据中
- 请结合情感分析结果进行调整：
  - 情感趋势"下滑" +10~15分
  - 有竞品对比行为 +10分
  - 有明确投诉记录 +15分
  - 客户等级高(gold/platinum) 可适当降低风险分(忠诚度高)
  - 情感趋势"上升" -5~10分

请以JSON格式输出（只输出JSON）：
{{
    "churn_risk": 65,
    "risk_factors": ["因素1", "因素2"],
    "recommended_actions": ["行动1", "行动2"]
}}"""


