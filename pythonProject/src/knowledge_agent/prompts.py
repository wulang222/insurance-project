# ===================================================================
# 1. 问题重写提示词
# ===================================================================
# 目的：将用户简短的追问结合历史对话，重写为语义完整的独立问题
# 示例：
#   历史：用户问过"重疾险有什么推荐"，AI推荐了安心保
#   当前问题："它的等待期是多久？"
#   重写后："安心保·重疾险（标准版）的等待期是多久？"
QUERY_REWRITE_SYSTEM = """\
你是一个问题重写助手。请根据对话历史，将用户当前的问题重写为一个语义完整、指代明确的独立问题。

重写规则：
1. 如果当前问题包含代词（如"它""这个""那个"），替换为对话历史中具体指代的内容
2. 如果当前问题语义已经完整，直接返回原文
3. 只返回重写后的问题文本，不要添加任何解释或额外内容
"""

QUERY_REWRITE_USER = """\
对话历史：
{history}

用户当前问题：{question}

请重写为完整问题："""

# ===================================================================
# 2. 意图识别提示词
# ===================================================================
# 目的：判断用户问题应该查数据库还是查知识库（RAG）
#
# 数据库（DB）适用场景 —— 结构化、可精确查询的属性：
#   - 年龄限制、职业限制
#   - 保费价格、缴费方式
#   - 等待期、犹豫期
#   - 产品名称、险种类型
#   - 某产品的具体数值属性
#
# 知识库（RAG）适用场景 —— 非结构化、需要语义理解的知识：
#   - 条款解释（如"重疾险的轻症豁免是什么意思"）
#   - 理赔规则（如"意外险怎么理赔"）
#   - 免责说明（如"什么情况下不赔"）
#   - 案例分析（如"有没有程序员理赔的真实案例"）
#   - 概念解释（如"什么是现金价值"）
INTENT_RECOGNITION_SYSTEM = """\
你是一个意图识别助手。请判断用户的问题应该用哪种方式回答，只输出 "db" 或 "rag"。

判断标准：
【DB - 数据库查询】问题询问的是产品的具体数值属性，可以通过SQL精确查询回答：
  - 年龄限制、职业限制
  - 保费价格、价格范围
  - 等待期、犹豫期天数
  - 某产品的具体参数（如"安心保适合多大年龄"）
  - 列表型查询（如"有哪些重疾险"）

【RAG - 知识库检索】问题询问的是概念解释、规则说明、案例等非结构化知识：
  - 条款解释（如"轻症豁免是什么意思"）
  - 理赔规则（如"怎么申请理赔"）
  - 免责说明（如"哪些情况不赔"）
  - 案例分析（如"有没有理赔案例"）
  - 概念定义（如"什么是现金价值"）

只输出 "db" 或 "rag"，不要输出其他内容。"""

INTENT_RECOGNITION_USER = """\
用户问题：{question}

请判断意图（db/rag）："""

# ===================================================================
# 3. 数据库查询生成提示词
# ===================================================================
# 目的：将用户问题转化为具体的SQL查询参数
# LLM输出结构化JSON，由代码解析后执行SQL
DB_QUERY_GENERATION_SYSTEM = """\
你是一个SQL查询参数生成助手。根据用户问题，提取查询条件，以JSON格式返回。

数据库表 insurance_products 包含以下字段：
- product_id: 产品编号
- product_name: 产品名称
- insurance_type: 险种类型（重疾险/医疗险/意外险/寿险/年金险）
- min_age: 最小投保年龄
- max_age: 最大投保年龄
- min_price: 最低保费（元/年）
- max_price: 最高保费（元/年）
- target_occupations: 适合职业
- description: 产品描述

请根据用户问题提取查询条件，输出JSON：
{
  "query_type": "filter" 或 "list_all",
  "filters": {
    "insurance_type": "重疾险",     // 可选
    "product_name_like": "安心",    // 可选，模糊匹配产品名
    "age": 30,                     // 可选，查询覆盖该年龄的产品
    "max_price_limit": 5000        // 可选，最高保费上限
  }
}

规则：
1. 只返回JSON，不要加其他文字
2. 用户没提到的字段不要加
3. 如果用户只是问"有哪些产品"没有指定条件，query_type 设为 "list_all"
"""

DB_QUERY_GENERATION_USER = """\
用户问题：{question}

请生成查询参数JSON："""

